/**
 * Represents the CEFR (Common European Framework of Reference for Languages) levels
 * used to describe language proficiency.
 *
 * - `A1` — Beginner: Can understand and use familiar everyday expressions.
 * - `A2` — Elementary: Can communicate in simple and routine tasks.
 * - `B1` — Intermediate: Can deal with most situations likely to arise while traveling.
 * - `B2` — Upper-Intermediate: Can interact with a degree of fluency and spontaneity.
 * - `C1` — Advanced: Can use language effectively and flexibly in social, academic, and professional situations.
 * - `C2` — Proficient: Can understand with ease virtually everything heard or read.
 * - `Empty` — Not specified.
 */
export enum ELevels {
  Empty = '',
  A1 = 'a1',
  A2 = 'a2',
  B1 = 'b1',
  B2 = 'b2',
  C1 = 'c1',
  C2 = 'c2',
}
